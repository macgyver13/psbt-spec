//! Renders report.json as report.md.

use serde_json::Value;

fn strings(v: &Value) -> Vec<String> {
    v.as_array().unwrap().iter().map(|s| s.as_str().map(str::to_owned).unwrap_or_else(|| s.to_string())).collect()
}

fn join(v: &Value, empty: &str) -> String {
    let items = strings(v);
    if items.is_empty() { empty.to_owned() } else { items.join(", ") }
}

/// The report's one corpus file name when there is only one, for short refs.
fn short(reference: &str, single: Option<&str>) -> String {
    match single {
        Some(file) => format!("#{}", reference.strip_prefix(file).and_then(|r| r.strip_prefix('#')).unwrap_or(reference)),
        None => reference.to_owned(),
    }
}

pub fn render(report: &Value) -> String {
    let single = {
        let files = report["corpus"].as_array().unwrap();
        if files.len() == 1 { files[0]["file"].as_str() } else { None }
    };
    let sh = |r: &Value| short(r.as_str().unwrap(), single);
    let spec_rev = report["spec"]["revision"].as_str().unwrap();
    let mut out = format!(
        "# {} PSBT behavior vs. psbt-spec {}\n\nGenerated by `psbt-spec evaluate` from `report.json`.\n\n",
        report["project"]["name"].as_str().unwrap(),
        &spec_rev[..7]
    );

    let (p, a) = (&report["project"], &report["adapter"]);
    out += "## Record\n\n";
    out += &format!(
        "- Specification revision: `{spec_rev}`{}, \"{}\"\n",
        if report["spec"]["dirty"] == true { " (tracked files modified)" } else { "" },
        report["spec"]["status"].as_str().unwrap()
    );
    out += &format!(
        "- Project and revision: {} {}, revision `{}`; adapter {} {} speaking `{}`\n",
        p["name"].as_str().unwrap(), p["version"].as_str().unwrap(), p["revision"].as_str().unwrap(),
        a["name"].as_str().unwrap(), a["version"].as_str().unwrap(), a["protocol"].as_str().unwrap()
    );
    out += &format!(
        "- Versions and extensions: declared BIPs {}; declared tasks {}\n",
        join(&report["declared"]["bips"], "none"), join(&report["declared"]["tasks"], "none")
    );
    for c in report["corpus"].as_array().unwrap() {
        out += &format!(
            "- Corpus: `{}`, bip_revision `{}`, {} vectors, sha256 `{}`\n",
            c["file"].as_str().unwrap(), c["bip_revision"].as_str().unwrap(), c["vectors"], c["sha256"].as_str().unwrap()
        );
    }
    out += "- Rules in scope: every General and Role rule in `rules.json` at the specification revision. Guidance, Reference and Definition entries carry no verdict.\n";
    out += "- Method: executed. Each vector was sent to the adapter; verdicts follow the verdict rules in `docs/report.md`. Project locations were not looked up.\n";
    out += &format!(
        "- Auditor and date: `psbt-spec evaluate`, {} to {}\n\n",
        report["started"].as_str().unwrap(), report["finished"].as_str().unwrap()
    );

    let s = &report["summary"];
    let (v, r, st) = (&s["vectors"], &s["rows"], &s["stages"]);
    out += "## Summary\n\n";
    out += &format!(
        "- Vectors: {} total, {} accepted, {} rejected, {} not run, {} withheld (task or BIP not declared)\n",
        v["total"], v["accepted"], v["rejected"], v["not_run"], v["withheld"]
    );
    out += &format!(
        "- Stage requests (an invalid vector put to the role that owns its General rule): {} total, {} accepted, {} rejected, {} not run, {} withheld\n",
        st["total"], st["accepted"], st["rejected"], st["not_run"], st["withheld"]
    );
    out += &format!("- Valid vectors passed: {} of {}\n", s["valid"]["passed"], s["valid"]["total"]);
    out += &format!(
        "- Rows: {} MATCH, {} STRICTER, {} LOOSER, {} NOT IMPLEMENTED, {} NOT RUN\n",
        r["MATCH"], r["STRICTER"], r["LOOSER"], r["NOT IMPLEMENTED"], r["NOT RUN"]
    );
    let rj = &s["rejects"];
    out += &format!(
        "- Rejections behind MATCH evidence: {} confirmed (the project named the rule), {} unconfirmed (it named no rule in rules.json)\n",
        rj["confirmed"], rj["unconfirmed"]
    );
    out += &format!(
        "- Rejections naming another rule than the vector's (no MATCH): {}; naming a rule ID not in rules.json: {}\n",
        rj["other_rule"], rj["unknown_rule"]
    );
    out += &format!(
        "- Confounded vectors rejected: {}; triage items: {}\n\n",
        s["confounded"].as_array().unwrap().len(), s["triage"].as_array().unwrap().len()
    );
    out += "Verdicts are defined in the report format (`docs/report.md`, Verdicts). This report never gives DIFFERENT STAGE; compare a rule's rows across operations to see it.\n\n";

    out += "## Rows\n\n| Rule ID | Operation | Versions / extensions | Verdict | Project location | Test evidence | Observed outcome | Notes |\n|---|---|---|---|---|---|---|---|\n";
    let vectors = report["vectors"].as_array().unwrap();
    // The answer a row's evidence vector gave under the row's task: its own,
    // or its stage request's.
    let outcome_of = |reference: &str, task: &Value| -> String {
        let v = vectors.iter().find(|v| v["ref"] == reference).unwrap();
        let stages = v.get("stages").and_then(Value::as_array).into_iter().flatten();
        let answer = if v["task"] == *task { v } else { stages.into_iter().find(|s| s["task"] == *task).unwrap() };
        match answer["outcome"].as_str().unwrap() {
            "accept" => "accepted".into(),
            "reject" => "rejected".into(),
            other => other.to_owned(),
        }
    };
    for row in report["rows"].as_array().unwrap() {
        let evidence = row["evidence"].as_array().unwrap();
        let refs: Vec<String> = evidence.iter().map(|e| sh(&e["vector"])).collect();
        let mut groups: Vec<(String, Vec<String>)> = Vec::new();
        for e in evidence {
            let (outcome, r) = (outcome_of(e["vector"].as_str().unwrap(), &row["task"]), sh(&e["vector"]));
            match groups.iter_mut().find(|(o, _)| *o == outcome) {
                Some((_, list)) => list.push(r),
                None => groups.push((outcome, vec![r])),
            }
        }
        let observed = if groups.is_empty() {
            "not run".to_owned()
        } else {
            groups.iter().map(|(o, l)| format!("{o} {}", l.join(", "))).collect::<Vec<_>>().join("; ")
        };
        let mut notes = row.get("notes").and_then(Value::as_str).unwrap_or_default().to_owned();
        for st in row["stale"].as_array().unwrap() {
            notes += &format!(
                "{}stale: evidence cites BIP {} at bips {}, but {} is labeled at {}",
                if notes.is_empty() { "" } else { "; " }, st["bip"], st["evidence"].as_str().unwrap(),
                st["file"].as_str().unwrap(), st["corpus"].as_str().unwrap()
            );
        }
        out += &format!(
            "| {} | {} | {} | {} | not located | {} | {} | {} |\n",
            row["rule"].as_str().unwrap_or("(none)"),
            row["task"].as_str().unwrap(),
            join(&row["bips"], "any"),
            strings(&row["verdicts"]).join(" and "),
            if refs.is_empty() { "none".to_owned() } else { refs.join(", ") },
            observed,
            notes.replace('|', "\\|")
        );
    }
    out += &match single {
        Some(file) => format!("\nVector numbers are indices into `{file}` (zero-based).\n"),
        None => "\nVectors are `<corpus file>#<index>` (zero-based).\n".to_owned(),
    };

    let describe = |v: &Value| format!("{} {}", sh(&v["ref"]), v["description"].as_str().unwrap());
    out += "\n## Confounded vectors\n\n";
    let confounded: Vec<&Value> = vectors.iter().filter(|v| s["confounded"].as_array().unwrap().contains(&v["ref"])).collect();
    if confounded.is_empty() {
        out += "None.\n";
    }
    for v in confounded {
        let named = v["evidence"].as_array().unwrap().iter().find(|e| e["verdict"] == "MATCH");
        let judged = match named {
            Some(e) => format!("Rejected naming {}, so only that rule gets evidence (MATCH)", e["rule"].as_str().unwrap()),
            None => match v.get("rule").and_then(Value::as_str) {
                Some(rule) => format!("Rejected naming {rule}, which is not one of them, so no rule gets evidence"),
                None => "Rejected, so no single rule gets evidence".to_owned(),
            },
        };
        out += &format!("- {}: fails {}. {judged}.\n", describe(v), join(&v["failed"], "none"));
    }

    out += "\n## Triage\n\n";
    let triage: Vec<&Value> = vectors.iter().filter(|v| s["triage"].as_array().unwrap().contains(&v["ref"])).collect();
    if triage.is_empty() {
        out += "None: every invalid vector fails at least one rule.\n";
    }
    for v in triage {
        let why = if v["class"] == "none" { "fails no rule".to_owned() } else { format!("only incomplete on {}", join(&v["incomplete"], "none")) };
        out += &format!("- {}: {why}; project outcome {}\n", describe(v), v["outcome"].as_str().unwrap());
    }

    out += "\n## Not run\n\n";
    let mut any = false;
    for v in vectors {
        let stages = v.get("stages").and_then(Value::as_array).into_iter().flatten();
        for a in std::iter::once(v).chain(stages).filter(|a| matches!(a["outcome"].as_str(), Some("n/a" | "error"))) {
            any = true;
            let outcome = match a.get("error").and_then(Value::as_str) {
                Some(kind) => format!("error ({kind})"),
                None => "n/a".to_owned(),
            };
            let stage = if a["task"] == v["task"] { String::new() } else { format!(" (stage request, {})", a["task"].as_str().unwrap()) };
            out += &format!("- {}{stage}: {outcome}, \"{}\"\n", describe(v), a["reason"].as_str().unwrap_or_default());
        }
    }
    if !any {
        out += "None.\n";
    }

    out += "\n## Unverified\n\n- Every verdict rests on the vectors run and on psbt-spec's attribution at the specification revision. A rule with no vector is NOT RUN, not MATCH.\n- Project locations were not looked up; a source review fills that column.\n";
    out
}
